  function sipsinOf(dayGan, targetGan) {
    if (!dayGan || !targetGan) return null;
    var de = GAN_ELEMENT[dayGan], te = GAN_ELEMENT[targetGan];
    var sameYY = GAN_YANG[dayGan] === GAN_YANG[targetGan];
    if (de === te) return sameYY ? '비견' : '겁재';
    if (GEN_NEXT[de] === te) return sameYY ? '식신' : '상관';
    if (CTRL_NEXT[de] === te) return sameYY ? '편재' : '정재';
    if (CTRL_NEXT[te] === de) return sameYY ? '편관' : '정관';
    if (GEN_NEXT[te] === de) return sameYY ? '편인' : '정인';
    return null;
  }
