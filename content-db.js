  function joinFrags(fragments, connectors, rng) {
    // fragments: string[] (완결 문장들). 2번째부터 접속어를 붙여 문단으로 이어 붙인다.
    var out = [];
    fragments.forEach(function (f, i) {
      if (!f) return;
      if (i === 0 || out.length === 0) out.push(f);
      else out.push(pick(rng, connectors) + f);
    });
    return out.join(' ');
  }

