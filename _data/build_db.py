# 유니코드 메일링리스트 기록(unicode.org/mail-arch, 1999)에 남아 있어 채택하지 않는다.
# → v1.7 벽자 제외 기준 = kIRG_KSource 가 K0 또는 K1 로 시작하는 글자만 인명 후보로 채택.
