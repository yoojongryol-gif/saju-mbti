# 이 코드가 어느 한국 표준에 등재됐는지를 밝히는데, 그중
#   K0 = KS X 1001:2004 (구 KS C 5601, 상용한자 4,888자)
#   K1 = KS X 1002:2001 (구 KS C 5657, 한자 부수·추가한자 2,856자)
# 는 실제 한국 국가표준(KS)으로 제정된 것이 실물로 확인되나, K2~K6(PKS C 5700 계열)는
