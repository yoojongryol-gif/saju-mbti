def resolve_comp(c):
    """구성요소 1글자 → (글자, 뜻, 음, 원형|None). 못 밝히면 None.

    hanja.txt 에 없는 조각(부수 변형·자형 단편)은 획수 3획 이상일 때만 채택한다.
    1~2획짜리 단편(𠃌·𠂉·丷 등)은 '뜻을 가진 요소'라기보다 획의 일부라
    파자 풀이에 넣으면 오히려 곡해를 부르기 때문이다.
    """
    r = resolve_component(c, COMP_CTX)
    if r:
        return r
    st = TOTAL_STROKES_ALL.get(ord(c)) if len(c) == 1 else None
    if st is None or st < 3:
        return None
    return resolve_component(c, COMP_CTX_FALLBACK)


def entry_parts(ch):
    """DB 글자 → (IDS문자열|None, 구성요소 리스트). 전부 밝혀질 때만 구성요소를 준다."""
    ids, parts = decompose_parts(ch, ids_map)
    if not parts or not (2 <= len(parts) <= 5):
        return (ids, [])
    for p in parts:
        r = resolve_comp(p)
        if not r:
            return (ids, [])
        # 구성요소가 글자 자신으로 되돌아오면(例 玉=王+丶에서 王→玉) 풀이가 순환한다
        if p == ch or RAD_FORMS.get(p) == ch:
            return (ids, [])
    return (ids, parts)


